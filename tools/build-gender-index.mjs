/** Small attested feminine-NOM index, from the already attributed Lexique 4.1. */
import fs from 'node:fs';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
const root=new URL('../',import.meta.url),source=new URL('data/references/Lexique4.1/Lexique4.1.tsv',root);
const bytes=fs.readFileSync(source),genders=new Map();
for(const line of bytes.toString('utf8').split(/\r?\n/u).slice(1)){
 const f=line.split('\t');if(f.length!==37||f[4]!=='NOM')continue;
 const w=f[0].normalize('NFC').toLocaleLowerCase('fr').replace(/’/gu,"'");
 if(!/^[a-zà-öø-ÿœæ]+(?:[-'][a-zà-öø-ÿœæ]+)*$/u.test(w))continue;
 if(!genders.has(w))genders.set(w,new Set());genders.get(w).add(f[6]||'?');
}
const feminine=[...genders].filter(([,s])=>s.size===1&&s.has('f')).map(([w])=>w).sort();
const gzip=zlib.gzipSync(Buffer.from(feminine.join('\n')),{level:9});
const stats={source:'Lexique 4.1',purpose:'Unambiguous attested feminine nouns only; no spelling-based gender guessing.',forms:feminine.length,gzipBytes:gzip.length,sourceSha256:crypto.createHash('sha256').update(bytes).digest('hex')};
fs.writeFileSync(new URL('src/gender-data.js',root),'// Generated by tools/build-gender-index.mjs. Source remains unchanged.\nexport const FEMININE_NOUN_B64='+JSON.stringify(gzip.toString('base64'))+';\nexport const FEMININE_NOUN_STATS='+JSON.stringify(stats)+';\n');
fs.writeFileSync(new URL('data/gender-index-audit.json',root),JSON.stringify(stats,null,2)+'\n');
console.log(JSON.stringify(stats));
